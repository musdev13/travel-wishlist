import * as Location from 'expo-location';
import { Alert } from 'react-native';

/**
 * Отримує поточні GPS-координати користувача.
 *
 * Алгоритм роботи:
 * 1. Запитує дозвіл на використання геопозиції під час роботи додатку (Foreground).
 * 2. Якщо користувач відхилив запит — показує системне попередження та повертає null.
 * 3. Якщо доступ надано — зчитує точні координати з датчиків пристрою.
 * 4. У разі апаратної помилки (вимкнений GPS, режим "У літаку") — перехоплює виняток і сповіщає про збій.
 *
 * @returns Об'єкт із широтою та довготою або null у разі відмови/помилки
 */
export const getUserCurrentLocation = async (): Promise<{ latitude: number; longitude: number } | null> => {
  try {
    // ------------------------------------------------------------------------
    // КРОК 1: Запит дозволу користувача у рантаймі
    // ------------------------------------------------------------------------
    // Метод requestForegroundPermissionsAsync запитує доступ до локації ТІЛЬКИ
    // тоді, коли додаток відкрито на екрані (Foreground).
    // Повертає об'єкт статусу: 'granted' (дозволено), 'denied' (відхилено) або 'undetermined'.
    const { status } = await Location.requestForegroundPermissionsAsync();

    // ------------------------------------------------------------------------
    // КРОК 2: Перевірка дозволу
    // ------------------------------------------------------------------------
    // Якщо користувач натиснув "Заборонити" (Don't Allow):
    if (status !== 'granted') {
      Alert.alert(
        'Доступ до геолокації відхилено',
        'Щоб показати ваше місцезнаходження на карті Хмельницького/Вінниці, надайте дозвіл у налаштуваннях вашого смартфона.'
      );
      return null;
    }

    // ------------------------------------------------------------------------
    // КРОК 3: Отримання одноразового знімка координат
    // ------------------------------------------------------------------------
    // getCurrentPositionAsync робить один точний вимір поточної точки.
    // Параметр accuracy: Balanced забезпечує баланс між точністю (до 10-50 метрів)
    // та швидкістю отримання сигналу без надмірного розряджання акумулятора.
    const location = await Location.getCurrentPositionAsync({
      accuracy: Location.Accuracy.Balanced,
    });

    // ------------------------------------------------------------------------
    // КРОК 4: Повернення координат
    // ------------------------------------------------------------------------
    return {
      latitude: location.coords.latitude,   // Широта точки
      longitude: location.coords.longitude, // Довгота точки
    };
  } catch (error) {
    // Обробка непередбачуваних помилок (наприклад, GPS повністю вимкнено в шторці ОС)
    console.error('Помилка під час отримання геолокації:', error);
    Alert.alert(
      'Помилка GPS',
      'Не вдалося визначити місцезнаходження. Переконайтеся, що служби геолокації увімкнено на пристрої.'
    );
    return null;
  }
};